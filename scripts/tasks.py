#!/usr/bin/env python3
"""Task tracker for docs/features/*.md.

Each feature file has a header, a `## Tracker` table (the source of truth for every task's status) and a `## Specs`
section with one `### <ID>: <title>` block per task. This script validates them and regenerates the index section of
docs/plan.md.

    scripts/tasks.py                     regenerate the index in docs/plan.md
    scripts/tasks.py --check             validate; fail if invalid or the index is stale (run by scripts/check.sh)
    scripts/tasks.py set ID STATUS [--branch B] [--round N] [--note TEXT]
                                         update one tracker row, then regenerate
    scripts/tasks.py show ID             print a task's feature file, tracker row and spec block
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FEATURES = ROOT / "docs" / "features"
PLAN = ROOT / "docs" / "plan.md"
BEGIN, END = "<!-- tasks:begin (generated by scripts/tasks.py; edit the feature files) -->", "<!-- tasks:end -->"

STATUSES = ["todo", "ready", "building", "review", "fixing", "merging", "blocked", "parked", "done"]
ACTIVE = {"building", "review", "fixing", "merging", "blocked"}
COLUMNS = ["Task", "Title", "Status", "Branch / merge", "Rounds", "Notes"]
ID = re.compile(r"^[TF]\d+[a-z]?$")


class Invalid(Exception):
    pass


def cells(line):
    parts = line.strip()
    if not (parts.startswith("|") and parts.endswith("|")):
        raise Invalid(f"not a table row: {line!r}")
    return [c.strip() for c in parts[1:-1].split("|")]


def row_line(row):
    return "| " + " | ".join(row) + " |"


class Feature:
    def __init__(self, path):
        self.path = path
        self.slug = path.stem
        self.text = path.read_text()
        lines = self.text.split("\n")
        if not lines[0].startswith("# "):
            raise Invalid(f"{path.name}: first line must be '# <title>'")
        self.title = lines[0][2:].strip()
        self.meta = {}
        for line in lines[1:]:
            if not line.strip():
                break
            key, _, value = line.partition(":")
            self.meta[key.strip()] = value.strip()
        for key in ("milestone", "goal"):
            if key not in self.meta:
                raise Invalid(f"{path.name}: header needs '{key}:'")
        try:
            start = lines.index("## Tracker")
        except ValueError:
            raise Invalid(f"{path.name}: no '## Tracker' section")
        i = start + 1
        while i < len(lines) and not lines[i].startswith("|"):
            i += 1
        if cells(lines[i]) != COLUMNS:
            raise Invalid(f"{path.name}: tracker columns must be {COLUMNS}")
        self.table_start = i
        i += 2
        self.rows = []
        while i < len(lines) and lines[i].startswith("|"):
            row = cells(lines[i])
            if len(row) != len(COLUMNS):
                raise Invalid(f"{path.name}: tracker row has {len(row)} cells (no '|' in notes): {lines[i]!r}")
            self.rows.append(row)
            i += 1
        self.table_end = i
        self.lines = lines
        self.specs = {}
        current = None
        in_specs = False
        for line in lines:
            if line == "## Specs":
                in_specs = True
                continue
            if not in_specs:
                continue
            m = re.match(r"^### ([TF]\d+[a-z]?): (.*)$", line)
            if m:
                current = m.group(1)
                if current in self.specs:
                    raise Invalid(f"{path.name}: duplicate spec {current}")
                self.specs[current] = [line]
            elif current:
                self.specs[current].append(line)

    def save(self):
        lines = self.lines[: self.table_start + 2] + [row_line(r) for r in self.rows] + self.lines[self.table_end :]
        self.path.write_text("\n".join(lines))


def load():
    features = [Feature(p) for p in sorted(FEATURES.glob("*.md")) if p.name != "README.md"]
    tasks = {}
    for f in features:
        for row in f.rows:
            tid = row[0]
            if not ID.match(tid):
                raise Invalid(f"{f.path.name}: bad task id {tid!r}")
            if tid in tasks:
                raise Invalid(f"{tid} is tracked in both {tasks[tid][0].path.name} and {f.path.name}")
            tasks[tid] = (f, row)
    return features, tasks


def validate(features, tasks):
    errors = []
    for f in features:
        tracked = {r[0] for r in f.rows}
        for tid in tracked - set(f.specs):
            errors.append(f"{f.path.name}: {tid} is in the tracker but has no '### {tid}:' spec")
        for tid in set(f.specs) - tracked:
            errors.append(f"{f.path.name}: spec {tid} is not in the tracker")
        for row in f.rows:
            tid, status, where = row[0], row[2], row[3]
            if status not in STATUSES:
                errors.append(f"{tid}: status {status!r} is not one of {STATUSES}")
            if status == "done" and not re.search(r"\b[0-9a-f]{7,40}\b|decision \d{4}", where):
                errors.append(f"{tid}: done needs its merge commit (or 'decision NNNN') in 'Branch / merge'")
        for tid, block in f.specs.items():
            for line in block:
                if line.startswith("depends:"):
                    for dep in re.findall(r"\b[TF]\d+[a-z]?\b", line):
                        if dep not in tasks:
                            errors.append(f"{tid}: depends on unknown task {dep}")
    return errors


def deps_of(f, tid):
    for line in f.specs.get(tid, []):
        if line.startswith("depends:"):
            return re.findall(r"\b[TF]\d+[a-z]?\b", line)
    return []


def index(features, tasks):
    out = [BEGIN, "", "## In flight", ""]
    out.append("| Task | Feature | Status | Branch / merge | Rounds | Notes |")
    out.append("|---|---|---|---|---|---|")
    for f in features:
        for r in f.rows:
            if r[2] in ACTIVE:
                out.append(row_line([f"{r[0]} {r[1]}", f"[{f.slug}](features/{f.slug}.md)", r[2], r[3], r[4], r[5]]))
    out += ["", "## Ready to start", "", "`ready` tasks, and `todo` tasks whose dependencies are all done.", ""]
    out.append("| Task | Feature | Status | Depends |")
    out.append("|---|---|---|---|")
    for f in features:
        for r in f.rows:
            deps = deps_of(f, r[0])
            unblocked = all(tasks[d][1][2] == "done" for d in deps if d in tasks)
            if r[2] == "ready" or (r[2] == "todo" and unblocked):
                out.append(row_line([f"{r[0]} {r[1]}", f"[{f.slug}](features/{f.slug}.md)", r[2], ", ".join(deps) or "–"]))
    out += ["", "## Features", ""]
    out.append("| Feature | Milestone | Done | Open | Goal |")
    out.append("|---|---|---|---|---|")
    for f in features:
        done = sum(r[2] == "done" for r in f.rows)
        open_ = sum(r[2] not in ("done", "parked") for r in f.rows)
        out.append(row_line([f"[{f.title}](features/{f.slug}.md)", f.meta["milestone"], str(done), str(open_), f.meta["goal"]]))
    out += ["", END]
    return "\n".join(out)


def render_plan(features, tasks):
    plan = PLAN.read_text()
    if BEGIN not in plan or END not in plan:
        raise Invalid(f"docs/plan.md needs the generated markers {BEGIN!r} and {END!r}")
    head, rest = plan.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + index(features, tasks) + tail


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    sub = p.add_subparsers(dest="cmd")
    s = sub.add_parser("set")
    s.add_argument("id")
    s.add_argument("status", choices=STATUSES)
    s.add_argument("--branch")
    s.add_argument("--round")
    s.add_argument("--note")
    sh = sub.add_parser("show")
    sh.add_argument("id")
    a = p.parse_args()
    try:
        features, tasks = load()
        if a.cmd == "set":
            if a.id not in tasks:
                raise Invalid(f"unknown task {a.id}")
            f, row = tasks[a.id]
            row[2] = a.status
            for value, col in ((a.branch, 3), (a.round, 4), (a.note, 5)):
                if value is not None:
                    row[col] = value.replace("|", "/")
            f.save()
            features, tasks = load()
        if a.cmd == "show":
            f, row = tasks[a.id]
            print(f"{f.path.relative_to(ROOT)}\n{row_line(row)}\n")
            print("\n".join(f.specs[a.id]).rstrip())
            return 0
        errors = validate(features, tasks)
        if errors:
            raise Invalid("\n".join(errors))
        new = render_plan(features, tasks)
        if a.check:
            if new != PLAN.read_text():
                raise Invalid("docs/plan.md's index is stale: run scripts/tasks.py")
        else:
            PLAN.write_text(new)
    except Invalid as e:
        print(f"tasks: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
